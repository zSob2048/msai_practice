s = "고기를 한번 잡아봐요"

# help(str)

# s가 고기를 이라는 말로 시작하는지
print(s.startswith("고기를"))

# s에서 한번->두번으로 바꿔서
print(s.replace("한번","두번"))

# s에서 '잡' 이 몇번째 위치에 있나
print(s.find("잡"))
print(s.index("잡"))
# 주어진 문자가 없을때는 출력값이 다름 (find: -1, index: ValueError)

# # s에서 두번째 글자
print(s[1])

# # s에 '봐' 라는 글자가 들어있나
print(s.find("봐") != -1)

# # s 글자수
print(len(s))

